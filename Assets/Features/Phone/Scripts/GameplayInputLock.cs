namespace GamePhone
{
    /// <summary>
    /// Отдано ли управление интерфейсу вместо игрока.
    ///
    /// Спрашивать обязано КАЖДОЕ игровое действие, а не только ходьба. Клавиши
    /// на клавиатуре одни и те же: пробел - это и прыжок, и пробел в тексте,
    /// а E в русской раскладке - это буква "е". Пока такой проверки не было,
    /// игрок, набирая в телефоне "едем на почту", подпрыгивал и заодно ложился
    /// спать, потому что рядом стояла кровать.
    ///
    /// Собрано в одном месте, чтобы при добавлении нового действия не надо было
    /// вспоминать все три условия заново.
    /// </summary>
    public static class GameplayInputLock
    {
        public static bool Blocked
        {
            get
            {
                // Игрок печатает в каком-нибудь поле - номер телефона, имя
                // контакта, запись в календаре, задача в списке дел
                if (UIFocusState.IsTypingInField()) return true;

                // Открыт телефон
                if (PhoneUIController.Instance != null && PhoneUIController.Instance.IsOpen) return true;

                // Поверх экрана висит окно с курсором: пауза мини-игры,
                // итоги смены, диалог выхода и тому подобное
                return CursorRequestState.AnyRequested;
            }
        }
    }
}
